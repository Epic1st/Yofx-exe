using System.Collections.Frozen;

namespace YO4X.StrategyGovernance;

/// <summary>
/// The MQL5 named compile-time constants: every enumeration member and every
/// free-standing named limit the compiler folds to a number.
///
/// <para>
/// Where the values come from. MetaQuotes does not publish them: every enumeration
/// table in the online reference has exactly two columns, an ID and a description,
/// and the numbers appear nowhere. So they were not read off the documentation and
/// they were not inferred from ordinal position - they were measured, by asking the
/// MQL5 compiler shipped with MetaTrader 5 what each name folds to.
/// </para>
///
/// <para>
/// The measurement. For each candidate name the probe compiles
/// <c>int v = (long)(NAME) + 4294967296;</c>. When <c>NAME</c> is a compile-time
/// constant the compiler folds the whole expression and refuses to store the result
/// in an <c>int</c>, emitting
/// <c>warning 44: truncation of constant value from 'long(X)' to 'int(Y)'</c>.
/// Subtracting the added 2^32 back off <c>X</c>, in wrapping 64-bit arithmetic,
/// gives the constant exactly, sign and width included. A name the compiler does
/// not know reports <c>error 256: undeclared identifier</c> instead and is dropped;
/// a name that is really a function reports <c>error 132</c> and is dropped too.
/// The extraction was re-run against a fresh, differently batched compilation for a
/// random sample and every value matched by literal substring.
/// </para>
///
/// <para>
/// Why this matters more than coverage. The enumerations are not safely ordinal and
/// the folk knowledge about them is wrong in both directions.
/// <c>ENUM_TRADE_REQUEST_ACTIONS</c> really is sparse - <c>TRADE_ACTION_DEAL</c> is
/// 1 and <c>TRADE_ACTION_CLOSE_BY</c> is 10, with gaps - so guessing ordinals there
/// would silently mis-compile trading logic. But <c>ORDER_FILLING_BOC</c>, which is
/// commonly said to have been inserted ahead of <c>ORDER_FILLING_RETURN</c>, is
/// measured at 3, after it: the filling modes are FOK 0, IOC 1, RETURN 2, BOC 3.
/// Neither fact is guessable, and both are now measured.
/// </para>
///
/// <para>
/// What is deliberately absent. Constants whose value is a <c>double</c> -
/// <c>EMPTY_VALUE</c>, <c>DBL_MAX</c>, <c>M_PI</c> and the rest of the floating
/// point limits - are not carried. The probe cannot tell them apart from integers
/// after folding, and <see cref="Mql5BuiltinConstant.Value"/> is an integer, so
/// carrying them would mean recording <c>M_PI</c> as 3. An absent name is a
/// diagnostic; a wrong value is a wrong program.
/// </para>
///
/// <para>
/// Two questions are answered separately. <see cref="TryGetValue"/> reports the
/// number. <see cref="TryGetDeclaringEnum"/> reports which MQL5 enumeration
/// declares the constant, which is what a binder needs to decide that
/// <c>POSITION_TYPE_BUY</c> may be passed where an <c>ENUM_POSITION_TYPE</c> is
/// expected. Membership was measured too, by compiling a call to
/// <c>void f(ENUM_X)</c> for a hypothesised enumeration and keeping the hypothesis
/// only when the compiler did not answer <c>error 262: cannot convert enum</c>.
/// A constant with no declaring enumeration - a colour, an error code, a limit -
/// reports false, as does one whose enumeration was never established.
/// </para>
/// </summary>
public static class Mql5BuiltinConstants
{
    private static readonly Mql5BuiltinConstant[] AllConstants = BuildConstants();

    private static readonly FrozenDictionary<string, Mql5BuiltinConstant> ConstantsByName =
        AllConstants.ToFrozenDictionary(constant => constant.Name, StringComparer.Ordinal);

    // Grouped in ascending value order, which for an MQL5 enumeration is declaration
    // order, so members come back the way the reference lists them.
    private static readonly FrozenDictionary<string, IReadOnlyList<Mql5BuiltinConstant>> ConstantsByEnum =
        AllConstants
            .Where(constant => constant.EnumName is not null)
            .GroupBy(constant => constant.EnumName!, StringComparer.Ordinal)
            .ToFrozenDictionary(
                group => group.Key,
                group => (IReadOnlyList<Mql5BuiltinConstant>)
                    [.. group.OrderBy(constant => constant.Value ?? long.MaxValue)
                            .ThenBy(constant => constant.Name, StringComparer.Ordinal)],
                StringComparer.Ordinal);

    private static readonly FrozenDictionary<string, IReadOnlyList<string>> MemberNamesByEnum =
        ConstantsByEnum.ToFrozenDictionary(
            pair => pair.Key,
            pair => (IReadOnlyList<string>)[.. pair.Value.Select(constant => constant.Name)],
            StringComparer.Ordinal);

    /// <summary>Every catalogued constant, ordinal-sorted by name.</summary>
    public static IReadOnlyList<Mql5BuiltinConstant> All => AllConstants;

    /// <summary>Every catalogued constant name, ordinal-sorted.</summary>
    public static IReadOnlyList<string> Names { get; } = [.. AllConstants.Select(constant => constant.Name)];

    /// <summary>Every MQL5 enumeration the catalog carries members for, ordinal-sorted.</summary>
    public static IReadOnlyList<string> EnumNames { get; } = [.. ConstantsByEnum.Keys.Order(StringComparer.Ordinal)];

    /// <summary>
    /// Resolves a named constant to its numeric value. Returns false both for a name
    /// the catalog does not know and for one whose value is not an integer - use
    /// <see cref="IsKnown"/> to tell those two cases apart.
    /// </summary>
    public static bool TryGetValue(string name, out long value)
    {
        ArgumentNullException.ThrowIfNull(name);

        if (ConstantsByName.TryGetValue(name, out Mql5BuiltinConstant? constant) && constant.Value is long known)
        {
            value = known;
            return true;
        }

        value = 0;
        return false;
    }

    /// <summary>
    /// Resolves a named constant to its value and its declaring MQL5 enumeration,
    /// where the constant has one.
    /// </summary>
    public static bool TryGet(string name, out Mql5BuiltinConstant constant)
    {
        ArgumentNullException.ThrowIfNull(name);

        if (ConstantsByName.TryGetValue(name, out Mql5BuiltinConstant? found))
        {
            constant = found;
            return true;
        }

        constant = null!;
        return false;
    }

    /// <summary>
    /// True when the catalog knows <paramref name="name"/> as a constant, whether or
    /// not its numeric value is carried.
    /// </summary>
    public static bool IsKnown(string name)
    {
        ArgumentNullException.ThrowIfNull(name);
        return ConstantsByName.ContainsKey(name);
    }

    /// <summary>
    /// Reports the MQL5 enumeration that declares <paramref name="name"/>. Returns
    /// false for a free-standing constant - a colour, an error code, a limit - and
    /// for one whose declaring enumeration was never established.
    /// </summary>
    public static bool TryGetDeclaringEnum(string name, out string enumName)
    {
        ArgumentNullException.ThrowIfNull(name);

        if (ConstantsByName.TryGetValue(name, out Mql5BuiltinConstant? constant) && constant.EnumName is not null)
        {
            enumName = constant.EnumName;
            return true;
        }

        enumName = string.Empty;
        return false;
    }

    /// <summary>Every catalogued member of one MQL5 enumeration, in declaration order.</summary>
    public static IReadOnlyList<Mql5BuiltinConstant> ByEnum(string enumName)
    {
        ArgumentNullException.ThrowIfNull(enumName);
        return ConstantsByEnum.TryGetValue(enumName, out IReadOnlyList<Mql5BuiltinConstant>? found) ? found : [];
    }

    /// <summary>
    /// The names of one MQL5 enumeration's members, in declaration order. Empty for
    /// an enumeration the catalog carries no members for.
    /// </summary>
    public static IReadOnlyList<string> MembersOf(string enumName)
    {
        ArgumentNullException.ThrowIfNull(enumName);
        return MemberNamesByEnum.TryGetValue(enumName, out IReadOnlyList<string>? found) ? found : [];
    }

    /// <summary>
    /// Merges the measured table with whatever the signature module declares.
    /// A measured entry always wins on value, because it was read off the compiler
    /// and the declared one was not; a declared entry contributes any name the probe
    /// never saw, and contributes its declaring enumeration where the probe could
    /// not establish one.
    /// </summary>
    private static Mql5BuiltinConstant[] BuildConstants()
    {
        Dictionary<string, Mql5BuiltinConstant> merged = new(StringComparer.Ordinal);

        foreach (Mql5BuiltinConstant declared in Mql5BuiltinSignatures.DeclareConstants())
        {
            merged[declared.Name] = declared;
        }

        foreach (Mql5BuiltinConstant measured in Mql5MeasuredConstants.Declare())
        {
            merged[measured.Name] = merged.TryGetValue(measured.Name, out Mql5BuiltinConstant? declared)
                ? measured with { EnumName = measured.EnumName ?? declared.EnumName }
                : measured;
        }

        return [.. merged.Values.OrderBy(constant => constant.Name, StringComparer.Ordinal)];
    }
}

